Texture2D fontTexture() {
    std::vector<u8> bytes = {};
    bytes.reserve(64 * 8 * 8);

    for (auto c : FONT) {
        for (auto y = 0; y < 7; y++) {
            auto line = c[y];
            for (auto x = 0; x < 7; x++) {
                bool fill = (line >> (6 - x)) & 1;
                if (fill) {
                    bytes.push_back(0xFF);
                } else {
                    bytes.push_back(0x00);
                }
            }

            bytes.push_back(0x00);
        }

        for (auto i = 0; i < 8; i++) {
            bytes.push_back(0x00);
        }
    }

    return Texture2D::create(8, 64 * 8, bytes.data(), true, false);
}
